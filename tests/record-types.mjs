import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
import {z} from 'zod';
import {routedSearchIntent} from '../app/search-intent.ts';
import {schemas} from '../app/validation.ts';
globalThis.recordTypeTest={z,schemas};
const source=readFileSync('app/record-types.ts','utf8').replace(/^import .*;\r?\n/gm,'');
const code=ts.transpileModule('const {z,schemas}=globalThis.recordTypeTest;'+source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {parseRecord,documentSchema}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const id=crypto.randomUUID();
const car={id,kind:'car',created:1,data:{name:'Audi A6',year:2014,engine:'3.0 TDI',vin:'',mileage:0,nextService:0}};
assert.equal(parseRecord(car).data.year,2014);
assert.throws(()=>parseRecord({...car,kind:'constructor'}));
assert.throws(()=>parseRecord({...car,data:{...car.data,year:'2014'}}));
assert.throws(()=>parseRecord({...car,kind:'expense'}));
const request={id,created:2,kind:'purchaseRequest',data:{carId:id,lines:[{title:'Brake pads',part:'Brake pads',oem:'GDB3373',quantity:1,dataMode:'inquiry',fitment:'unverified'}],status:'draft',vehicle:'Audi A6 2014',vin:'WAUZZZ4G5EN130128'}};
assert.equal(parseRecord(request).data.vin,request.data.vin);
assert.equal(parseRecord(request).data.vehicle,request.data.vehicle);
assert.equal(parseRecord(request).data.note,'');
assert.throws(()=>parseRecord({...request,data:{...request.data,vin:undefined}}));
const doc={id,name:'Receipt.pdf',size:100,mime:'application/pdf',created:1,carId:null};
assert.equal(documentSchema.parse(doc).carId,undefined);
assert.equal(documentSchema.parse({...doc,carId:id}).carId,id);
console.log('PASS: record discriminators, malformed records, purchase VIN snapshot and unlinked receipts');

assert.equal(routedSearchIntent('waU zzz4g5en130128','vin').text,'WAUZZZ4G5EN130128');
assert.equal(routedSearchIntent('стукає двигун','problem').kind,'problem');
assert.equal(routedSearchIntent('GDB3373','part').kind,'oem');
assert.equal(routedSearchIntent('стук','part').kind,'part');
