import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(s,c,next){if(s==='./vehicle-search')return next('./vehicle-search.ts',c);try{return next(s,c);}catch(e){if(s.startsWith('.')&&!s.endsWith('.ts'))return next(s+'.ts',c);throw e;}}});
const {extractOffers,matchesCatalogNumber,matchesVehicle,headlightMismatch}=await import('../app/product-offers.ts');
const url='https://prom.ua/p-real-product.html';
const product=(name,extra={})=>'<script type="application/ld+json">'+JSON.stringify({'@type':'Product',name,...extra})+'</script>';
assert.ok(matchesCatalogNumber({title:'Фара Audi 4G0 941 030 C'},'4G0941030C'));
assert.ok(matchesCatalogNumber({title:'Фара Audi 4G0-941-030-C'},'4G0 941 030 C'));
const alt=extractOffers(product('Фара Audi A6', {additionalProperty:[{name:'Cross reference numbers',value:'4G0941030C'}]}),url,'фара Audi A6','4G0941030C');
assert.equal(alt[0]?.matchClass,'alternative_oem');
const noPrice=extractOffers(product('Фара Audi A6', {mpn:'4G0941030C'}),url,'фара Audi A6','4G0941030C');
assert.equal(noPrice.length,1);assert.equal(noPrice[0].price,undefined);assert.equal(noPrice[0].url,url);
const priced=extractOffers(product('Фара Audi A6', {mpn:'4G0941030C',offers:{'@type':'Offer',price:'12500.50',priceCurrency:'UAH'}}),url,'фара Audi A6','4G0941030C');
assert.equal(priced[0].price,12500.5);
const dynamic=extractOffers('<h1>Фара Audi A6 4G0941030C</h1><script>window.price=""</script>',url,'фара Audi A6','4G0941030C');
assert.equal(dynamic.length,1);assert.equal(dynamic[0].availability,'Наявність уточнюйте');assert.equal(dynamic[0].price,undefined);
assert.equal(headlightMismatch('Headlight Audi A6 right LED','ліва фара LED'),'side');
assert.equal(matchesVehicle('Фара Audi A6 C6 2008','AUDI A6 C7 2014','A6'),false);
assert.equal(extractOffers(product('Фара Audi A6', {sku:'4G0941030C'}),url,'фара Audi A6','4G0941030C')[0].matchClass,'exact_oem');
console.log('PASS: exact/normalized/alternative OEM, no-price and dynamic-price product pages, JSON-LD price, headlight side and generation safeguards');
